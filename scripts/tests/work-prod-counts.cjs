const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('work/work.js', 'utf8');
const context = vm.createContext({});
const from = source.indexOf('function bundleCountSummary(');
const to = source.indexOf('const bundleTitle', from);
vm.runInContext(`const has = v => typeof v === 'number' && Number.isFinite(v);
const total = list => list.length && list.every(has) ? list.reduce((a,b) => a+b,0) : undefined;
const num = v => Number(v).toLocaleString('ko-KR');
const UNK = '<span>미확인</span>';
const esc = s => String(s);
` + source.slice(from,to), context);
const summary = (rows, expected, label='공정 칸') => context.bundleCountSummary(rows, expected, label);
assert.match(summary([{'문항': null}],0), /대조 보류/);
assert.doesNotMatch(summary([{'문항': null}],0), /맞음|합 0/);
assert.match(summary([{'문항': 20},{}],20), /미확인/);
assert.match(summary([{'문항': 0}],0), /합 0.*맞음/);
assert.match(summary([],0), /합 0.*맞음/);
assert.match(summary([{'문항': 20},{'문항': 3}],23), /합 23.*맞음/);
assert.match(summary([{'문항': 20}],23), /어긋남/);
assert.equal(summary([{'문항': 20}],null), '목록 문항 합 20');
assert.match(summary([{'문항': 20}],20,'작업자 칸'), /작업자 칸과 맞음/);
console.log('work production count regressions: 9 PASS');
