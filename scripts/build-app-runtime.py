#!/usr/bin/env python3
"""Build ordered classic-script bundles without hiding the core's global lexical bindings.

Each non-core source is an IIFE or an explicit window assignment (see the reviewed
manifest). A per-source function preserves its strict-mode directive; call(window)
keeps classic-script top-level this, and independent error reporting lets later
sources initialize just as separate script tags did. The core stays a separate
classic script because its lexical bindings are shared by later renderer wrappers.
Run after changing an original runtime source; generated URLs include content hashes.
"""
import hashlib,json,re,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent
INDEX=ROOT/'app/index.html'
MANIFEST=ROOT/'scripts/app-runtime-sources.json'
html=INDEX.read_text()
if not MANIFEST.exists():
 body=html[html.index('<body'):]
 urls=re.findall(r'<script\s+src="([^"]+)"[^>]*></script>',body)
 core=next(u for u in urls if u.split('?')[0]=='deltaskill-next.js')
 n=urls.index(core)
 MANIFEST.write_text(json.dumps({'before-core':urls[:n],'core':core,'after-core':urls[n+1:]},ensure_ascii=False,indent=2)+'\n')
manifest=json.loads(MANIFEST.read_text())
def versioned(url):
 return url.split('?')[0] + '?v=' + hashlib.sha256(source_path(url).read_bytes()).hexdigest()[:12]

def source_path(url):
 return ROOT/url.split('?')[0].lstrip('/') if url.startswith('/') else ROOT/'app'/url.split('?')[0]
paths = [str(source_path(url)) for group in ['before-core', 'after-core'] for url in manifest[group]]
compact = json.loads(subprocess.check_output(
    ['node', str(ROOT / 'scripts/compact-runtime.cjs')], input=json.dumps(paths), text=True
))
versions={}
for group in ['before-core','after-core']:
 parts=['/* Generated by scripts/build-app-runtime.py. Edit original sources, then rebuild. */\n']
 for url in manifest[group]:
  source=source_path(url).read_text()
  reviewed=re.sub(r'^\s*(?:(?:/\*.*?\*/|//[^\n]*\n)\s*)*', '', source, flags=re.S)
  reviewed=re.sub(r'^[\"\']use strict[\"\'];?\s*', '', reviewed)
  if not re.match(r'(?:\(|!function|window\.)', reviewed):
   raise SystemExit('New global declarations need separate script review: '+url)
  parts.append('\n;/* Original classic script: '+url+' */\ntry { (function () {\n'+compact[str(source_path(url))]+'\n}).call(window); } catch (error) {\n  if (typeof window.reportError === "function") window.reportError(error);\n  else setTimeout(function () { throw error; }, 0);\n}\n')
 text=''.join(parts)
 output=ROOT/'app'/('runtime-'+group+'.js')
 output.write_text(text)
 versions[group]=hashlib.sha256(text.encode()).hexdigest()[:12]
core_path=source_path(manifest['core'])
core_url=manifest['core'].split('?')[0]+'?v='+hashlib.sha256(core_path.read_bytes()).hexdigest()[:12]
for group in ['before-core','after-core']:
 tag='<script defer data-runtime-bundle="'+group+'" src="runtime-'+group+'.js?v='+versions[group]+'"></script>'
 # Keep inert source descriptors for the existing student retry logic, which
 # discovers original URLs through document.scripts. Unknown script types do not
 # execute or fetch; retrySource creates an ordinary script only after a failure.
 descriptors=''.join('<script type="application/x-deltaskill-source" data-runtime-source="'+group+'" src="'+versioned(url)+'"></script>' for url in manifest[group])
 html=re.sub(r'<script\b[^>]*data-runtime-source="'+group+r'"[^>]*></script>', '', html)
 tag+=descriptors
 pattern=r'<script\b[^>]*data-runtime-bundle="'+group+r'"[^>]*></script>'
 if re.search(pattern,html):html=re.sub(pattern,lambda m:tag,html)
 else:
  for n,url in enumerate(manifest[group]):
   original=r'<script\s+src="'+re.escape(url)+r'"[^>]*></script>'
   if not re.search(original,html):raise SystemExit('Missing original script: '+url)
   html=re.sub(original,lambda m:tag if n==0 else '',html,count=1)
html=re.sub(r'<script\b[^>]*src="deltaskill-next\.js(?:\?[^" ]*)?"[^>]*></script>',lambda m:'<script defer src="'+core_url+'"></script>',html,count=1)
INDEX.write_text(html)
print('Built ordered runtime: '+str(sum(len(manifest[g]) for g in ['before-core','after-core']))+' sources → 2 bundles; global core separate. '+json.dumps(versions))
