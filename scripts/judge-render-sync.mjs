// Copies the draw card's own markup cleaner (cleanBody · dress and their allow-lists) out of
// app/runtime-after-core.js into review-d7q4m2/render-copy.js, letter for letter, so the review board
// shows an item exactly as the draw does (no second renderer).  `--check` fails if the copy drifted.
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const root = new URL('..', import.meta.url).pathname;
const srcPath = root + 'app/runtime-after-core.js', outPath = root + 'review-d7q4m2/render-copy.js';
const src = readFileSync(srcPath, 'utf8');
const anchor = src.indexOf('function cleanBody(html,solution){');
if (anchor < 0) throw Error('cleanBody not found');
const lineStart = src.lastIndexOf('\n', anchor) + 1, line = src.slice(lineStart, src.indexOf('\n', anchor) === -1 ? src.length : src.indexOf('\n', anchor));
function fn(name) {
  const i = line.indexOf('function ' + name + '(');
  if (i < 0) throw Error(name + ' not found');
  let depth = 0, quote = null, regexOk = false;
  for (let k = line.indexOf('{', i); k < line.length; k++) {
    const c = line[k];
    if (quote) { if (c === '\\') { k++; continue; } if (c === quote) quote = null; continue; }
    if (c === '"' || c === "'" || c === '`') { quote = c; continue; }
    if (c === '/' && regexOk) { // skip a regex literal
      for (k++; k < line.length && line[k] !== '/'; k++) { if (line[k] === '\\') k++; else if (line[k] === '[') { for (k++; line[k] !== ']'; k++) if (line[k] === '\\') k++; } }
      while (/[a-z]/.test(line[k + 1])) k++;
      regexOk = false; continue;
    }
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (!depth) return line.slice(i, k + 1); }
    if (!/\s/.test(c)) regexOk = /[(,=:[!&|?{};+\-*%<>~^]/.test(c) || (c === 'n' && line.slice(k - 5, k + 1) === 'return');
  }
  throw Error(name + ' unterminated');
}
function decl(name) {
  const m = line.match(new RegExp('const ' + name + '=(?:"[^"]*"(?:,[A-Z_]+="[^"]*")*|new Set\\("[^"]*"\\.split\\(" "\\)\\))'));
  if (!m) throw Error(name + ' not found');
  return m[0] + ';';
}
const parts = [decl('HTML_NS'), decl('htmlTags'), decl('mathTags'), decl('mathAttrs'), decl('keepClass'), fn('cleanBody'), fn('dress')];
if (!parts[0].includes('MATH_NS=')) throw Error('MATH_NS not with HTML_NS');
const body = parts.join('\n');
for (const p of parts) if (!src.includes(p.replace(/;$/, ''))) throw Error('copy differs from source');
const sha = createHash('sha256').update(body).digest('hex');
const out = '/* Generated by scripts/judge-render-sync.mjs from app/runtime-after-core.js — do not edit.\n   The draw card cleaner, letter for letter (sha256 ' + sha + '). */\n(()=>{"use strict";\n' + body +
  '\nwindow.DSJudgeRender=Object.freeze({question:html=>cleanBody(html,false),solution:html=>cleanBody(html,true),sha:"' + sha + '"});})();\n';
if (process.argv.includes('--check')) {
  const now = readFileSync(outPath, 'utf8');
  if (now !== out) { console.error('render-copy.js differs from app/runtime-after-core.js — run node scripts/judge-render-sync.mjs'); process.exit(1); }
  console.log('render-copy ok ' + sha);
} else { writeFileSync(outPath, out); console.log('render-copy written ' + sha); }
